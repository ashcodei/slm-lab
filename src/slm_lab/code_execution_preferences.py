"""Public-example-verified preferences over our own incorrect code generations."""
from collections import Counter
import json
from pathlib import Path

from .code_quality import execute, instruction_code
from .corpus import file_hash
from .diverse_images import atomic_json, jsonl


def prepare(data, diagnostic, checkpoint, output):
    data, diagnostic, checkpoint, output = map(Path, [data, diagnostic, checkpoint, output])
    source = json.loads((data.parent / 'manifest.json').read_text())
    generated = json.loads(diagnostic.read_text())
    if (file_hash(data) != source['train_sha256'] or generated['data_sha256'] != file_hash(data)
            or generated['checkpoint_sha256'] != file_hash(checkpoint)
            or not generated['exact_language_and_critic_preserved']):
        raise ValueError('Own generation/source identities differ')
    configuration = {'training_data_sha256': file_hash(data), 'diagnostic_sha256': file_hash(diagnostic),
                     'own_checkpoint_sha256': file_hash(checkpoint), 'implementation_sha256': file_hash(__file__)}
    output.mkdir(parents=True, exist_ok=True)
    if any(output.iterdir()):
        raise ValueError('Use a fresh execution-preference dataset directory')
    original = {row['id']: row for row in jsonl(data)}
    pairs = []; excluded = Counter(); seen = set()
    for result in generated['results']:
        if result['candidate']['functional_passed']:
            excluded['generation already passes published examples'] += 1
            continue
        row = original[result['id']]
        if row['original_program_sha256'] != result['original_program_sha256'] or row['function'] != result['function']:
            raise ValueError('Generation diagnostic and source program differ')
        if row['original_program_sha256'] in seen:
            raise ValueError('Repeated source algorithm in diagnostic')
        chosen, rejected = row['response'], result['raw_response']
        if not rejected.strip() or chosen == rejected:
            excluded['empty or identical response'] += 1
            continue
        def check(text):
            return execute({'language': 'Python', 'code': instruction_code(text), 'function': row['function'],
                            'cases': row['verification_cases'], 'stress': []})
        gold = check(chosen); bad = check(rejected)
        if not gold.get('functional_passed'):
            raise ValueError('Public preferred implementation no longer passes its source examples')
        if bad.get('functional_passed'):
            raise ValueError('Own rejected generation now passes; preference is not reproducible')
        seen.add(row['original_program_sha256'])
        pairs.append({key: value for key, value in row.items() if key not in {'response', 'annotation_origin'}} |
                     {'chosen': chosen, 'rejected': rejected, 'feedback_source': 'synthetic',
                      'feedback_origin': 'Execution on published source examples: public reference passes; our own generation fails.',
                      'own_generation_checkpoint_sha256': generated['checkpoint_sha256'],
                      'own_generation_diagnostic_sha256': file_hash(diagnostic),
                      'verification': {'preferred': gold, 'rejected': bad},
                      'annotation_origin': 'Original public instruction/code/examples; rejected response generated by our own from-scratch policy. No human preference rating or external teacher.'})
    if not pairs:
        raise ValueError('No reproducibly incorrect own generations retained')
    (output / 'train.jsonl').write_text(''.join(json.dumps(row, ensure_ascii=False) + '\n' for row in pairs))
    manifest = {'configuration': configuration, 'train_examples': len(pairs),
                'unique_source_algorithms': len(seen), 'feedback_source': 'synthetic',
                'train_sha256': file_hash(output / 'train.jsonl'), 'excluded': dict(excluded),
                'human_feedback': False, 'external_teacher_used': False, 'goal_achieved': False,
                'scope': 'Execution-derived coding preference experiment; not genuine human RLHF.',
                'limitations': ['Small examples selected after observing failures on actual training programs.',
                                'Passing published examples does not prove algorithmic correctness or efficiency.',
                                'Wrong syntax/runtime/values are combined; these are not independently human-rated preferences.',
                                'Fresh final-policy generations and broader held-out tests remain necessary before scale-up or promotion.']}
    atomic_json(output / 'manifest.json', manifest)
    return manifest
